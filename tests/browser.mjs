import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch({headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader','--enable-webgl']});
const url=pathToFileURL(resolve('index.html')).href;
const errors=[];
try {
  const page=await browser.newPage({viewport:{width:1366,height:850},deviceScaleFactor:1});
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
  await page.goto(url);
  await page.waitForFunction(()=>document.querySelector('#renderStatus').textContent.includes('جاهز'),{},{timeout:30000});
  await page.waitForFunction(()=>document.querySelector('#earthStatus').textContent.includes('3/3'),{},{timeout:30000});
  await page.waitForTimeout(500);
  assert.equal(await page.locator('#modules button').count(),6);
  assert.equal(await page.locator('#progress').textContent(),'0 / 4');
  // Verify a real framebuffer contains rendered geometry, not only the background.
  const pixels=await page.evaluate(()=>{
    const canvas=document.getElementById('gl'),gl=canvas.getContext('webgl');
    return new Promise(resolve=>requestAnimationFrame(()=>{
      const w=canvas.width,h=canvas.height,b=new Uint8Array(w*h*4);
      gl.readPixels(0,0,w,h,gl.RGBA,gl.UNSIGNED_BYTE,b);
      let lit=0,bright=0;for(let i=0;i<b.length;i+=4){if(b[i]+b[i+1]+b[i+2]>65)lit++;if(b[i]+b[i+1]+b[i+2]>300)bright++}
      resolve({lit,bright,total:w*h,error:gl.getError()});
    }));
  });
  console.log('Framebuffer:',pixels);
  assert.equal(pixels.error,0);
  assert.ok(pixels.lit>pixels.total*.015,'Expected visible 3D objects');
  assert.ok(pixels.bright>100,'Expected lit geometry');
  await page.screenshot({path:'artifacts/desktop.png'});
  await page.locator('#modules button').nth(0).click();
  await page.locator('#detail button').click();
  await page.locator('#modules button').nth(1).click();
  await page.locator('#detail button').click();
  assert.equal(await page.locator('#progress').textContent(),'2 / 4');
  await page.locator('#light').evaluate(e=>{e.value=100;e.dispatchEvent(new Event('input',{bubbles:true}))});
  await page.waitForFunction(()=>document.querySelector('#progress').textContent==='3 / 4');
  await page.locator('#tour').click();
  assert.equal(await page.locator('#tour').getAttribute('aria-pressed'),'true');
  await page.locator('#tour').click();
  await page.locator('#explode').click();
  await page.waitForFunction(()=>document.querySelector('#progress').textContent==='4 / 4');
  await page.locator('#paths').click();
  assert.equal(await page.locator('#paths').getAttribute('aria-pressed'),'true');
  await page.screenshot({path:'artifacts/exploded.png'});
  await page.locator('#light').evaluate(e=>{e.value=0;e.dispatchEvent(new Event('input',{bubbles:true}))});
  await page.waitForFunction(()=>document.querySelector('#generation').textContent==='36 kW');
  assert.match(await page.locator('#warning').textContent(),/عجز/);
  await page.locator('#play').click();
  const battery=await page.locator('#battery').textContent();
  await page.waitForTimeout(500);
  assert.equal(await page.locator('#battery').textContent(),battery);
  await page.locator('#restart').click();
  assert.equal(await page.locator('#progress').textContent(),'0 / 4');
  await page.locator('#quality').selectOption('cinema');
  await page.waitForTimeout(300);
  await page.screenshot({path:'artifacts/cinema.png'});
  await page.locator('#quality').selectOption('low');
  await page.locator('#pilot').click();
  assert.equal(await page.locator('#pilot').getAttribute('aria-pressed'),'true');
  await page.locator('#autodock').click();
  await page.waitForFunction(()=>document.querySelector('#flightMessage').textContent.includes('التحام ناجح'),{},{timeout:60000});
  await page.screenshot({path:'artifacts/docking.png'});
  await page.locator('#camera').selectOption('top');
  assert.equal(await page.locator('#pilot').getAttribute('aria-pressed'),'false');
  await page.locator('#camera').selectOption('planet');
  await page.waitForTimeout(1000);
  await page.screenshot({path:'artifacts/earth.png'});
  await page.locator('#camera').selectOption('sun');
  await page.waitForTimeout(1000);
  await page.screenshot({path:'artifacts/sun.png'});
  await page.close();
  const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  mobile.on('pageerror',e=>errors.push(e.message));
  await mobile.goto(url);
  await mobile.waitForFunction(()=>document.querySelector('#renderStatus').textContent.includes('جاهز'));
  assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'No horizontal overflow');
  await mobile.screenshot({path:'artifacts/mobile.png',fullPage:true});
  await mobile.locator('#pilot').click();
  const checkCockpit = async (p) => {
    const bounds = await p.evaluate(()=>{
      const scene=document.querySelector('#stage').getBoundingClientRect(), toolbar=document.querySelector('.dock').getBoundingClientRect(), flight=document.querySelector('#flightPanel').getBoundingClientRect();
      return {sceneBottom:scene.bottom,toolbarTop:toolbar.top,toolbarBottom:toolbar.bottom,flightTop:flight.top,overflow:document.documentElement.scrollWidth-innerWidth,touch:getComputedStyle(document.querySelector('#gl')).touchAction};
    });
    assert.ok(bounds.sceneBottom<=bounds.toolbarTop+1,'Toolbar does not obscure canvas');
    assert.ok(bounds.toolbarBottom<=bounds.flightTop+1,'Flight controls do not obscure canvas or toolbar');
    assert.ok(bounds.overflow<=1,'No horizontal overflow');
    assert.equal(bounds.touch,'pan-y','Default allows native vertical scrolling');
  };
  await checkCockpit(mobile);
  await mobile.locator('#flightCollapse').click();
  assert.equal(await mobile.locator('#flightBody').isVisible(),false);
  await mobile.locator('#flightCollapse').click();
  assert.equal(await mobile.locator('#flightBody').isVisible(),true);
  await mobile.locator('#touchMode').click();
  assert.equal(await mobile.locator('#gl').evaluate(e=>getComputedStyle(e).touchAction),'none');
  await mobile.locator('#touchMode').click();
  await mobile.screenshot({path:'artifacts/mobile-pilot.png',fullPage:true});
  const landscape=await browser.newPage({viewport:{width:760,height:360},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  landscape.on('pageerror',e=>errors.push(e.message));
  await landscape.goto(url);
  await landscape.waitForFunction(()=>document.querySelector('#renderStatus').textContent.includes('جاهز'));
  await landscape.locator('#pilot').click();
  await checkCockpit(landscape);
  await landscape.evaluate(()=>window.scrollTo(0,0));
  const cdp=await landscape.context().newCDPSession(landscape);
  const b=await landscape.locator('#gl').boundingBox();
  const x=Math.round(b.x+20),y=Math.round(Math.min(b.y+b.height-12,340));
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]});
  for(let i=1;i<=8;i++){
    await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x,y:y-i*15}]});
    await landscape.waitForTimeout(30);
  }
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await landscape.waitForFunction(()=>scrollY>20,{},{timeout:5000});
  await landscape.locator('#controlJump').click();
  await landscape.waitForFunction(()=>document.querySelector('#controlCenter').getBoundingClientRect().top<100);
  await landscape.screenshot({path:'artifacts/landscape-controls.png'});
  await landscape.evaluate(()=>window.scrollTo(0,0));
  await landscape.screenshot({path:'artifacts/landscape-pilot.png',fullPage:true});
  await landscape.close();
  assert.deepEqual(errors,[]);
  console.log('PASS: actual WebGL framebuffer, interaction, mission, energy, pause, reset, responsive mobile');
} finally { await browser.close() }
